/**
 * The `.doru` project database schema.
 *
 * This is Dóru's own domain model, designed around the entities a genealogy
 * tree needs — not a mirror of the GEDCOM wire format. The subject-area
 * knowledge collected while building the `@doru/gedcom` parser/model/exporter
 * (records, facts, names, citations, dates) shaped the model; the schema
 * itself stays minimal and grows column by column as features demand.
 *
 * GEDCOM HEAD/SUBN metadata and raw extension/vendor record structures are
 * intentionally not stored (see docs/decisions.md); import counts them as
 * dropped and export synthesizes a fresh header.
 *
 * Conventions:
 * - Every record id is a UUID generated by the application. The `xref`
 *   column keeps the identifier a GEDCOM import assigned to the record, for
 *   round-trip export provenance; it has no meaning inside Dóru.
 * - Enum-like columns (`sex`, fact `tag`, `date_quality`, …) are plain TEXT
 *   without CHECK constraints so that unknown future values never brick a
 *   file (the same forward-compatibility rule as the settings schema).
 * - Every addressable row — including link rows (`family_partner`,
 *   `family_child`) — carries its own UUID, so the polymorphic attachment
 *   tables can point at anything.
 * - Dates live in one normalized `date` table. Every date row belongs to
 *   exactly one owner row and one role (`owner_type`, `owner_id`, `role`);
 *   owner triggers delete its date rows on delete. Ordering is derived in
 *   TypeScript from the date components. See `model/types.ts`.
 * - Names are normalized into `person_name` rows plus `name_part` piece rows
 *   (any number of given names, surnames, …). The flat pieces exposed by the
 *   model (given, surname, …) are projections of the parts.
 * - Places are first-class entities with hierarchical names
 *   (`place_name` rows, one jurisdiction per row).
 * - Notes, citations and media attach to their targets through a
 *   `(target_type, target_id)` pair — the polymorphic attachment shape, kept
 *   plain so SQLite needs no polymorphic FK tricks.
 * - There are no search index tables yet: person search scans the stored
 *   name parts until the dedicated search layer lands.
 * - Family children and partners carry a `position` so their order survives
 *   round-trips.
 */

